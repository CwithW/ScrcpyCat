import { readdir, readFile, mkdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const frontend = resolve(root, 'frontend/web-app')
const output = resolve(root, 'backend/internal/webui/dist')
const lock = JSON.parse(await readFile(resolve(frontend, 'package-lock.json'), 'utf8'))
const fallbacks = {
  h264decoder: ['h264decoder', 'tinyh264'],
  'opus-decoder': ['wasm-audio-decoders', 'opus'],
  '@wasm-audio-decoders/common': ['wasm-audio-decoders'],
  '@vue/devtools-api': ['vue-devtools']
}
const sections = ['ScrcpyCat frontend third-party licenses\n']

async function append(title, file) {
  sections.push(`\n${'='.repeat(78)}\n${title}\n${'='.repeat(78)}\n`, await readFile(file, 'utf8'))
}

await append('ScrcpyCat NOTICE', resolve(root, 'NOTICE'))
await append('ScrcpyCat LICENSE', resolve(root, 'LICENSE'))
await append('Frontend source (MIT)', resolve(root, 'frontend/LICENSE'))

let count = 0
for (const [directory, pkg] of Object.entries(lock.packages).sort(([a], [b]) => a.localeCompare(b))) {
  if (!directory || pkg.dev) continue
  const name = pkg.name || directory.split('node_modules/').at(-1)
  const files = (await readdir(resolve(frontend, directory))).filter(file => /^(licen[cs]e|notice|copying)(\.|$)/i.test(file)).sort()
  if (!files.length && !fallbacks[name]) throw new Error(`Missing license for ${name}@${pkg.version}`)
  for (const file of files) await append(`${name}@${pkg.version} — ${file}`, resolve(frontend, directory, file))
  for (const fallback of fallbacks[name] || []) {
    await append(`${name}@${pkg.version} — ${fallback}`, resolve(root, 'third_party/licenses', fallback, 'LICENSE'))
  }
  count++
}

await mkdir(output, { recursive: true })
await writeFile(resolve(output, '.keep'), 'Frontend assets are generated by make build-frontend.\n')
await writeFile(resolve(output, 'THIRD_PARTY_LICENSES.txt'), sections.join('\n'))
console.log(`Collected frontend licenses for ${count} npm packages`)
